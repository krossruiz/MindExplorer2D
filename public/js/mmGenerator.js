/**
 * mmGenerator.js - Generate .mm files from analysis
 * Converts structured data to FreeMind/Freeplane XML format
 */

class MMGenerator {
    constructor() {
        this.nodeIdCounter = 0;
    }

    /**
     * Generate a unique node ID
     */
    generateNodeId() {
        return 'ID_' + (++this.nodeIdCounter).toString().padStart(10, '0');
    }

    /**
     * Reset ID counter
     */
    resetIdCounter() {
        this.nodeIdCounter = 0;
    }

    /**
     * Escape XML special characters
     */
    escapeXml(text) {
        if (!text) return '';
        return text
            .replace(/&/g, '&amp;')
            .replace(/</g, '&lt;')
            .replace(/>/g, '&gt;')
            .replace(/"/g, '&quot;')
            .replace(/'/g, '&apos;');
    }

    /**
     * Generate .mm file from hierarchical structure
     * @param {Object} structure - Hierarchical structure with root node
     * @param {Object} options - Generation options
     */
    generate(structure, options = {}) {
        this.resetIdCounter();

        const {
            version = '1.0.1',
            includeTimestamps = true,
            colorScheme = 'default'
        } = options;

        let xml = `<map version="${version}">\n`;
        xml += '<!-- Generated by MindMapExplorer2D -->\n';

        if (structure.root) {
            xml += this.generateNode(structure.root, 0, includeTimestamps, colorScheme);
        }

        xml += '</map>\n';

        return xml;
    }

    /**
     * Generate XML for a single node and its children
     */
    generateNode(node, depth, includeTimestamps, colorScheme) {
        const indent = '  '.repeat(depth + 1);
        const nodeId = this.generateNodeId();
        const timestamp = Date.now();

        let attrs = `ID="${nodeId}" TEXT="${this.escapeXml(node.text)}"`;

        if (includeTimestamps) {
            attrs += ` CREATED="${timestamp}" MODIFIED="${timestamp}"`;
        }

        // Add position for first-level children
        if (depth === 1 && node.position) {
            attrs += ` POSITION="${node.position}"`;
        }

        // Add color if specified
        const color = this.getNodeColor(depth, colorScheme);
        if (color) {
            attrs += ` BACKGROUND_COLOR="${color}"`;
        }

        // Check if node has children
        const hasChildren = node.children && node.children.length > 0;

        if (!hasChildren) {
            return `${indent}<node ${attrs}/>\n`;
        }

        let xml = `${indent}<node ${attrs}>\n`;

        // Alternate positions for first-level children
        node.children.forEach((child, index) => {
            const childNode = { ...child };
            if (depth === 0) {
                childNode.position = index % 2 === 0 ? 'right' : 'left';
            }
            xml += this.generateNode(childNode, depth + 1, includeTimestamps, colorScheme);
        });

        xml += `${indent}</node>\n`;

        return xml;
    }

    /**
     * Get color for node based on depth and color scheme
     */
    getNodeColor(depth, scheme) {
        const schemes = {
            default: null,
            blue: ['#1a365d', '#2b4a7c', '#3c5f9e', '#4d74c0', '#5e89e2'],
            green: ['#1a4d1a', '#2d6b2d', '#408940', '#53a753', '#66c566'],
            warm: ['#7c2d12', '#9a3412', '#c2410c', '#ea580c', '#f97316'],
            purple: ['#4c1d95', '#5b21b6', '#6d28d9', '#7c3aed', '#8b5cf6']
        };

        const colors = schemes[scheme];
        if (!colors) return null;

        return colors[Math.min(depth, colors.length - 1)];
    }

    /**
     * Generate from chat messages
     */
    async generateFromChat(messages, customization = '') {
        // Use Claude to generate structure
        const structure = await window.claudeApi.generateMindMapStructure(messages, customization);
        return this.generate(structure);
    }

    /**
     * Generate from simple text list
     */
    generateFromList(title, items) {
        const structure = {
            root: {
                text: title,
                children: items.map(item => {
                    if (typeof item === 'string') {
                        return { text: item, children: [] };
                    }
                    return item;
                })
            }
        };

        return this.generate(structure);
    }

    /**
     * Generate from selected groups
     */
    generateFromGroups(groups, title = 'Group Analysis') {
        const structure = {
            root: {
                text: title,
                children: groups.map(group => ({
                    text: group.name,
                    children: group.nodes.map(node => ({
                        text: node.text,
                        children: []
                    }))
                }))
            }
        };

        return this.generate(structure);
    }

    /**
     * Download generated .mm file
     */
    download(xmlContent, filename = 'mindmap.mm') {
        const blob = new Blob([xmlContent], { type: 'application/xml' });
        const url = URL.createObjectURL(blob);

        const link = document.createElement('a');
        link.href = url;
        link.download = filename.endsWith('.mm') ? filename : filename + '.mm';
        document.body.appendChild(link);
        link.click();
        document.body.removeChild(link);

        URL.revokeObjectURL(url);
    }

    /**
     * Validate generated XML structure
     */
    validate(xmlContent) {
        try {
            const parser = new DOMParser();
            const doc = parser.parseFromString(xmlContent, 'text/xml');

            const parseError = doc.querySelector('parsererror');
            if (parseError) {
                return { valid: false, error: parseError.textContent };
            }

            const map = doc.querySelector('map');
            if (!map) {
                return { valid: false, error: 'Missing <map> element' };
            }

            const root = map.querySelector('node');
            if (!root) {
                return { valid: false, error: 'Missing root node' };
            }

            return { valid: true };
        } catch (e) {
            return { valid: false, error: e.message };
        }
    }

    /**
     * Merge multiple mind maps into one
     */
    mergeMindMaps(mindMaps, newRootText = 'Merged Mind Map') {
        const structure = {
            root: {
                text: newRootText,
                children: mindMaps.map(mm => ({
                    text: mm.root.text,
                    children: mm.root.children
                }))
            }
        };

        return this.generate(structure);
    }

    /**
     * Extract structure from parsed mind map (for re-export)
     */
    extractStructure(parsedMindMap) {
        const extractNode = (node) => ({
            text: node.text,
            children: node.children.map(extractNode)
        });

        return {
            root: extractNode(parsedMindMap.root)
        };
    }
}

// Create singleton instance
window.mmGenerator = new MMGenerator();
